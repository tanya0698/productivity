#!/usr/bin/env node
/**
 * Generates apps/mobile/src/features/registry.ts from the module folders.
 *
 * The web app discovers modules with Vite's import.meta.glob; Metro has no
 * equivalent, so this keeps the same rule — creating
 * apps/mobile/src/features/<key>/config/module.ts registers the module —
 * by writing the import list for you. It runs before `npm start` and
 * `npm run typecheck` in apps/mobile. Never edit registry.ts by hand.
 */
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const featuresDir = join(root, "apps", "mobile", "src", "features");

const keys = readdirSync(featuresDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(featuresDir, d.name, "config", "module.ts")))
  .map((d) => d.name)
  .sort();

const ident = (k) => k.replace(/-(\w)/g, (_, c) => c.toUpperCase()) + "Module";

const out = `/**
 * GENERATED by scripts/emit-mobile-modules.mjs — do not edit.
 * Add a module by creating src/features/<key>/config/module.ts.
 */
import type { MobileModuleManifest } from "../shared/modules/types";
${keys.map((k) => `import ${ident(k)} from "./${k}/config/module";`).join("\n")}

export const modules: MobileModuleManifest[] = [${keys.map(ident).join(", ")}];
`;

writeFileSync(join(featuresDir, "registry.ts"), out);
console.log(`[modules] mobile registry: ${keys.join(", ") || "(none)"}`);
